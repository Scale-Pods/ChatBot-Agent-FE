-- Run this in the Supabase SQL editor if the tables do not exist yet.

create table if not exists public."Users_CB" (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  "Name" text null,
  "Email" text null,
  "Password" text null,
  constraint "Users_CB_pkey" primary key (id)
) tablespace pg_default;

-- Logins look users up by email, so make sure it is unique and fast to find.
create unique index if not exists "Users_CB_Email_key"
  on public."Users_CB" (lower("Email"));

create table if not exists public."Chat Data" (
  id bigint generated by default as identity not null,
  session_id uuid not null default gen_random_uuid (),
  role text null,
  content text null,
  created_at timestamp with time zone null default now(),
  "Name" text null,
  "Phone" text null,
  "Email" text null,
  "Status" text null,
  "Agent" text null,
  constraint "Chat Data_pkey" primary key (id)
) tablespace pg_default;

create index if not exists "Chat Data_session_id_idx"
  on public."Chat Data" (session_id);

create index if not exists "Chat Data_created_at_idx"
  on public."Chat Data" (created_at desc);

-- Booked meetings shown on the Meetings page.
create table if not exists public."Meetings_Chatbot" (
  name text null,
  phone text null,
  email text null,
  consulting_for text null,
  on_date text null,
  time_received text null,
  meeting_link text null
) tablespace pg_default;

create index if not exists "Meetings_Chatbot_time_received_idx"
  on public."Meetings_Chatbot" (time_received);

-- Scheduled calls. A null `status` means the customer has not been contacted.
create table if not exists public."Phone_Chatbot" (
  phone text null,
  name text null,
  time_received text null,
  reason text null,
  status text null,
  email text null
) tablespace pg_default;

create index if not exists "Phone_Chatbot_time_received_idx"
  on public."Phone_Chatbot" (time_received);

create index if not exists "Phone_Chatbot_phone_idx"
  on public."Phone_Chatbot" (phone);
